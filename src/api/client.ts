// 通用请求方法
export async function request(path: string, options: RequestInit = {}) {
  await waitForApiReady();
  const token = getToken();
  const headers: HeadersInit = {
    'Content-Type': 'application/json',
    ...(options.headers || {}),
  };
  if (token) {
    (headers as any)['Authorization'] = `Bearer ${token}`;
  }
  const url = isAccountRoute(path) ? accountUrl(path) : `${API_BASE}${path}`;
  const res = await fetch(url, { ...options, headers });
  if (res.status === 401) {
    handleUnauthorized();
    throw new Error('认证失效');
  }
  if (!res.ok) {
    const errorData = await res.json().catch(() => ({}));
    throw new Error(errorData.error || `Request failed: ${res.status}`);
  }
  return res;
}

// 系统状态（检测 git-bash 等运行时依赖）
export async function getSystemStatus(): Promise<{
  platform: string;
  gitBash?: { required: boolean; found: boolean; path: string | null };
}> {
  await waitForApiReady();
  const res = await fetch(`${API_BASE}/system-status`);
  if (!res.ok) throw new Error('Failed to get system status');
  return res.json();
}

